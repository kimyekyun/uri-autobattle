const { chromium } = require("playwright");
const fs = require("fs"), path = require("path");
const dir = path.resolve(process.argv[2]), out = process.argv[3];
const mini = fs.readFileSync(path.join(__dirname, "mini-three.js"), "utf8");
(async () => {
  const b = await chromium.launch({ args: ["--use-gl=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
  const p = await b.newPage({ viewport: { width: 1180, height: 820 } });
  const errs = []; p.on("pageerror", (e) => errs.push(String(e.stack || e).slice(0, 500)));
  await p.route("**/*", (r) => { const u = r.request().url(); if (u.startsWith("file:")) return r.continue(); if (u.includes("three.min.js")) return r.fulfill({ contentType: "text/javascript", body: mini }); return r.abort(); });
  await p.goto("file://" + dir + "/index.html"); await p.waitForTimeout(1200);
  await p.click("#practice"); await p.waitForTimeout(900);
  await p.screenshot({ path: out + "-plan.png" });
  await p.click("#ready"); await p.waitForTimeout(1500);
  await p.screenshot({ path: out + "-fight.png" });
  const st = await p.evaluate(() => ({ phase: S.phase, n: S.battle.f.length, foes: S.battle.f.filter((f) => f.team === 1).map((f) => f.mon ? f.mon.mn : DEFS[f.d].n) }));
  console.log(JSON.stringify(st));
  await p.waitForTimeout(1500); await p.click("#pracstop"); await p.waitForTimeout(300);
  console.log(await p.evaluate(() => JSON.stringify({ phase: S.phase, banner: S.banner && S.banner.text, hp: human().hp, gold: human().gold })));
  await p.waitForFunction(() => S.phase === "plan", null, { timeout: 60000 });
  console.log(await p.evaluate(() => JSON.stringify({ phase: S.phase })));
  await p.click('#prac [data-foe="team"]'); await p.click('#prac [data-star="3"]'); await p.waitForTimeout(300);
  await p.click("#ready"); await p.waitForTimeout(2000);
  await p.screenshot({ path: out + "-team.png" });
  console.log(await p.evaluate(() => JSON.stringify({ phase: S.phase, star: S.battle.f.filter((f) => f.team === 0).map((f) => DEFS[f.d].n + f.star), foes: S.battle.f.filter((f) => f.team === 1).length })));
  await p.click("#pracexit"); await p.waitForTimeout(300);
  console.log(await p.evaluate(() => JSON.stringify({ ov: $("ov").hidden, prac: $("prac").hidden })));
  console.log("errors:", JSON.stringify([...new Set(errs)].slice(0, 5), null, 1));
  await b.close();
})();
